import { PinyinChar } from '../types';

// Generate HTML suited for Word Export (Table based)
const generateExportHtml = (result: PinyinChar[]) => {
    // Group into rows of 18 characters (Optimized for A4/Letter margins)
    const rows = [];
    let currentRow = [];
    const CHARS_PER_ROW = 18;

    for (let i = 0; i < result.length; i++) {
        currentRow.push(result[i]);
        if (currentRow.length === CHARS_PER_ROW || i === result.length - 1) {
            rows.push(currentRow);
            currentRow = [];
        }
    }

    const tableRows = rows.map(row => {
        // Pad the row with empty cells if it's shorter than CHARS_PER_ROW
        // This prevents Word from stretching the last few characters across the whole page
        const cellsNeeded = CHARS_PER_ROW - row.length;
        const paddedRow = [...row];
        for (let i = 0; i < cellsNeeded; i++) {
            paddedRow.push({ char: '', pinyin: '' }); // Placeholder
        }

        const cells = paddedRow.map(item => {
            if (!item.char) {
                // Empty spacer cell
                return `<td style="padding: 2px;"></td>`;
            }
            return `
            <td style="text-align: center; padding: 2px;">
                <div style="font-family: Arial, sans-serif; font-size: 9pt; color: #ea580c; min-height: 14px;">${item.pinyin || '&nbsp;'}</div>
                <div style="font-family: 'Microsoft YaHei', 'SimHei', sans-serif; font-size: 14pt; color: #000; line-height: 1.2;">${item.char}</div>
            </td>
        `}).join('');
        return `<tr>${cells}</tr>`;
    }).join('');

     return `
    <html xmlns:o='urn:schemas-microsoft-com:office:office' xmlns:w='urn:schemas-microsoft-com:office:word' xmlns='http://www.w3.org/TR/REC-html40'>
    <head>
        <meta charset="UTF-8">
        <title>Panda Lingo Export</title>
        <style>
            /* Define standard page margins to prevent clipping */
            @page {
                mso-page-orientation: portrait;
                margin: 1in 1in 1in 1in;
                mso-header-margin: 0.5in;
                mso-footer-margin: 0.5in;
            }
            /* Removed width: 100% to prevent stretching */
            table { border-collapse: collapse; }
            td { vertical-align: bottom; }
        </style>
    </head>
    <body>
        <div style="text-align: center; margin-bottom: 20px;">
            <h1 style="color: #ea580c; font-family: Arial, sans-serif;">Panda Lingo Output</h1>
        </div>
        <!-- Removed align="center" to prevent left-side clipping on wider tables -->
        <table>
            ${tableRows}
        </table>
        <div style="margin-top: 30px; font-size: 10px; color: #888; text-align: center;">Generated by Panda Lingo</div>
    </body>
    </html>
    `;
};

export const exportToWord = (result: PinyinChar[], filename: string = 'panda-lingo') => {
    if (result.length === 0) return;
    const htmlContent = generateExportHtml(result);
    const blob = new Blob(['\ufeff', htmlContent], {
        type: 'application/msword'
    });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${filename}-${Date.now()}.doc`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
};

export const exportToPdf = (result: PinyinChar[], filename: string = 'panda-lingo') => {
     if (result.length === 0) return;
     const element = document.createElement('div');
     element.innerHTML = generateExportHtml(result);
     element.style.padding = "20px";
     
     const opt = {
        margin: 10,
        filename: `${filename}-${Date.now()}.pdf`,
        image: { type: 'jpeg', quality: 0.98 },
        html2canvas: { scale: 2 },
        jsPDF: { unit: 'mm', format: 'a4', orientation: 'portrait' }
     };

     if ((window as any).html2pdf) {
         (window as any).html2pdf().from(element).set(opt).save();
     } else {
         alert("PDF Generator is loading, please try again in a second.");
     }
};

export const exportToEpub = async (result: PinyinChar[], title: string = "Panda Lingo Learning", filename: string = 'panda-lingo') => {
    if (result.length === 0 || !(window as any).JSZip) return;

    const zip = new (window as any).JSZip();
    const uuid = `urn:uuid:${Date.now()}`;

    // 1. mimetype
    zip.file("mimetype", "application/epub+zip");

    // 2. META-INF/container.xml
    zip.file("META-INF/container.xml", `<?xml version="1.0" encoding="UTF-8" ?>
        <container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">
            <rootfiles>
                <rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/>
            </rootfiles>
        </container>`);

    // 3. Content XHTML with Ruby tags
    // Process paragraphs to avoid one huge block
    let htmlBodyContent = '';
    let currentParagraph = '';
    
    result.forEach((item) => {
        // Render char with ruby
        let renderedItem = item.char;
        if (item.pinyin) {
            renderedItem = `<ruby>${item.char}<rt>${item.pinyin}</rt></ruby>`;
        }
        
        currentParagraph += renderedItem;
        
        // Split on newlines to make paragraphs
        if (item.char === '\n' || item.char === '\r') {
             htmlBodyContent += `<p>${currentParagraph}</p>`;
             currentParagraph = '';
        }
    });
    // Add remaining
    if (currentParagraph) {
        htmlBodyContent += `<p>${currentParagraph}</p>`;
    }

    const xhtml = `<?xml version="1.0" encoding="UTF-8" standalone="no"?>
        <!DOCTYPE html>
        <html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops" xml:lang="zh" lang="zh">
        <head>
            <title>${title}</title>
            <style>
                body { font-family: sans-serif; line-height: 2; font-size: 1.2em; padding: 20px; }
                ruby { ruby-align: center; }
                rt { font-size: 0.5em; color: #ea580c; }
                p { margin-bottom: 1em; text-align: justify; }
            </style>
        </head>
        <body>
            <h1>${title}</h1>
            ${htmlBodyContent}
        </body>
        </html>`;

    zip.folder("OEBPS").file("page.xhtml", xhtml);

    // 4. OEBPS/content.opf
    const opf = `<?xml version="1.0" encoding="UTF-8"?>
        <package xmlns="http://www.idpf.org/2007/opf" unique-identifier="BookId" version="3.0">
            <metadata xmlns:dc="http://purl.org/dc/elements/1.1/">
                <dc:title>${title}</dc:title>
                <dc:language>zh</dc:language>
                <dc:identifier id="BookId">${uuid}</dc:identifier>
            </metadata>
            <manifest>
                <item id="page" href="page.xhtml" media-type="application/xhtml+xml"/>
                <item id="ncx" href="toc.ncx" media-type="application/x-dtbncx+xml"/>
            </manifest>
            <spine toc="ncx">
                <itemref idref="page"/>
            </spine>
        </package>`;
    
    zip.folder("OEBPS").file("content.opf", opf);

    // 5. OEBPS/toc.ncx
    const ncx = `<?xml version="1.0" encoding="UTF-8"?>
        <ncx xmlns="http://www.daisy.org/z3986/2005/ncx/" version="2005-1">
            <head><meta name="dtb:uid" content="${uuid}"/></head>
            <docTitle><text>${title}</text></docTitle>
            <navMap>
                <navPoint id="navPoint-1" playOrder="1">
                    <navLabel><text>Start</text></navLabel>
                    <content src="page.xhtml"/>
                </navPoint>
            </navMap>
        </ncx>`;
    
    zip.folder("OEBPS").file("toc.ncx", ncx);

    // Generate blob
    const content = await zip.generateAsync({ type: "blob" });
    
    // Download
    const url = URL.createObjectURL(content);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${filename}-${Date.now()}.epub`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
};

export const exportToHtml = (result: PinyinChar[], filename: string = 'panda-lingo') => {
    if (result.length === 0) return;
    const htmlContent = generateExportHtml(result);
    const blob = new Blob([htmlContent], { type: 'text/html' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${filename}-${Date.now()}.html`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
};